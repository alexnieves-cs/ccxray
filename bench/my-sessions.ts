// Aggregate, measured-first summary of YOUR OWN Claude Code logs, for bench/MY_SESSIONS.md.
// LOCAL ONLY: never run in CI, and review the file before committing it.
//
//   pnpm my-sessions                      # default roots (CLAUDE_CONFIG_DIR, ~/.claude …), all time
//   pnpm my-sessions --since 2026-10-01   # a window (YYYY-MM-DD, UTC)
//   pnpm my-sessions --root DIR --out FILE
//
// Privacy: the output holds aggregate counts only. No paths, project names, prompts, commands,
// file names, session ids, turn ids or finding titles: findings are reduced to their analyzer id
// (a fixed name from src/analyzers), a count and a token sum with its [M]/[E] label.
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';
import { defaultRoots } from '../src/discover.js';
import { DEFAULT_THRESHOLDS, type Report } from '../src/model/index.js';
import { loadSessions } from '../src/parser/index.js';
import { buildReport } from '../src/pipeline.js';
import { VERSION } from '../src/version.js';

export interface AnalyzerRow {
  analyzer: string;
  findings: number;
  /** Sum of Finding.tokens.value with kind measured. */
  measured: number;
  /** Sum of Finding.tokens.value with kind estimated. */
  estimated: number;
}

export interface Aggregate {
  sessions: number;
  subagentSessions: number;
  turns: number;
  input: number;
  cacheWrite: number;
  cacheRead: number;
  output: number;
  cacheHitRatio: number | null;
  ccVersions: number;
  analyzers: AnalyzerRow[];
}

/** Reduce a report to counts. Nothing that names a project, path, file, session or command. */
export function aggregate(r: Report): Aggregate {
  const by = new Map<string, AnalyzerRow>();
  for (const f of r.findings) {
    // Analyzer ids are fixed names; anything unexpected is bucketed rather than printed.
    const id = /^[a-z0-9-]{1,40}$/.test(f.analyzer) ? f.analyzer : 'other';
    const row = by.get(id) ?? { analyzer: id, findings: 0, measured: 0, estimated: 0 };
    row.findings++;
    const v = Number.isFinite(f.tokens.value) ? f.tokens.value : 0;
    if (f.tokens.kind === 'measured') row.measured += v;
    else row.estimated += v;
    by.set(id, row);
  }
  const a = r.totals.all;
  return {
    sessions: r.sessions.filter((s) => !s.isSubagent).length,
    subagentSessions: r.sessions.filter((s) => s.isSubagent).length,
    turns: a.turns,
    input: a.input,
    cacheWrite: a.cacheWrite,
    cacheRead: a.cacheRead,
    output: a.output,
    cacheHitRatio: a.cacheHitRatio,
    ccVersions: new Set(r.sessions.flatMap((s) => s.ccVersions)).size,
    analyzers: [...by.values()].sort((x, y) => (x.analyzer < y.analyzer ? -1 : 1)),
  };
}

const n = (x: number): string => String(Math.round(x)).replace(/\B(?=(\d{3})+(?!\d))/g, ',');

export function toMarkdown(g: Aggregate, o: { since: string | null; generatedAt: string }): string {
  const pct = g.cacheHitRatio === null ? 'n/a' : `${(g.cacheHitRatio * 100).toFixed(1)}%`;
  const rows = g.analyzers.map(
    (r) =>
      `| ${r.analyzer} | ${r.findings} | ${r.measured > 0 ? `${n(r.measured)} [M]` : '-'} | ` +
      `${r.estimated > 0 ? `${n(r.estimated)} [E]` : '-'} |`,
  );
  return [
    '# My sessions (aggregate)',
    '',
    `Generated by \`pnpm my-sessions\` (ccxray ${VERSION}) on ${o.generatedAt.slice(0, 10)}, ` +
      `window: ${o.since === null ? 'all time' : `since ${o.since}`}.`,
    'Aggregate counts only: no paths, project names, prompts or ids.',
    '',
    '[M] = measured (summed from `usage` fields). [E] = estimated (chars/4 heuristic or an',
    "attribution guess). Findings' token sums overlap between analyzers and are not savings.",
    '',
    '## Totals [M]',
    '',
    '| metric | value |',
    '|---|---:|',
    `| sessions | ${n(g.sessions)} |`,
    `| subagent transcripts | ${n(g.subagentSessions)} |`,
    `| assistant turns | ${n(g.turns)} |`,
    `| Claude Code versions | ${n(g.ccVersions)} |`,
    `| input (uncached) tokens | ${n(g.input)} |`,
    `| cache write tokens | ${n(g.cacheWrite)} |`,
    `| cache read tokens | ${n(g.cacheRead)} |`,
    `| output tokens | ${n(g.output)} |`,
    `| cache hit ratio, read / (read + write + input) | ${pct} |`,
    '',
    '## Findings per analyzer',
    '',
    '| analyzer | findings | tokens [M] | tokens [E] |',
    '|---|---:|---:|---:|',
    ...(rows.length > 0 ? rows : ['| (none) | 0 | - | - |']),
    '',
  ].join('\n');
}

/** CLI entry; `log` gets the Markdown and a note on stderr-like channel. Exported for tests. */
export async function main(
  argv: string[],
  log: { out: (s: string) => void; err: (s: string) => void } = {
    out: (s) => void process.stdout.write(s),
    err: (s) => void process.stderr.write(s),
  },
): Promise<number> {
  const { values } = parseArgs({
    args: argv,
    options: {
      root: { type: 'string', multiple: true },
      since: { type: 'string' },
      out: { type: 'string' },
    },
    strict: true,
  });
  if (values.since !== undefined && !/^\d{4}-\d{2}-\d{2}$/.test(values.since)) {
    log.err('--since expects YYYY-MM-DD\n');
    return 2;
  }
  const since = values.since !== undefined ? new Date(`${values.since}T00:00:00.000Z`) : undefined;
  const now = new Date();
  const { sessions, stats } = await loadSessions({
    roots: values.root ?? defaultRoots(),
    ...(since !== undefined ? { since } : {}),
    includeContent: false,
  });
  const report = buildReport({
    sessions,
    stats,
    ctx: { thresholds: DEFAULT_THRESHOLDS, now, includeContent: false },
    window: { since: values.since ?? null, until: null, project: null },
    includeContent: false,
  });
  const md = toMarkdown(aggregate(report), {
    since: values.since ?? null,
    generatedAt: now.toISOString(),
  });
  const out = resolve(values.out ?? resolve(import.meta.dirname, 'MY_SESSIONS.md'));
  writeFileSync(out, md);
  log.out(md);
  log.err(`\nwrote ${out}; review it before committing.\n`);
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  main(process.argv.slice(2)).then(
    (code) => process.exit(code),
    (e: unknown) => {
      process.stderr.write(`${e instanceof Error ? e.message : String(e)}\n`);
      process.exit(1);
    },
  );
}
